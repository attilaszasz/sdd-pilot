const defineCommand = ({
  command,
  workflow,
  category,
  prerequisites = [],
  mutability = "workspace-write",
  mutationPolicy = null,
  argumentHint,
  emptyArgument,
  controls = [],
  copilotAgent,
  description,
}) => Object.freeze({
  command,
  workflow,
  category,
  prerequisites: Object.freeze([...prerequisites]),
  mutability,
  mutationPolicy,
  invocation: "user-only",
  arguments: Object.freeze({
    mode: "optional",
    hint: argumentHint,
    empty: emptyArgument,
    controls: Object.freeze([...controls]),
  }),
  canonicalWorkflow: `.github/sddp/workflows/${workflow}/WORKFLOW.md`,
  hostRoles: Object.freeze({
    copilot: copilotAgent,
    opencode: "build",
  }),
  description,
});

